"""Regenerate `.agents/roadmap/index.md` from the ledgers beside it.

A roadmap ledger is the one place a workstream's status, open work and measured
numbers live; AGENTS.md and the rules point at a ledger instead of restating
it. The index is how a reader finds the right ledger without opening the
directory, and it is generated, so it cannot drift from the files the way a
hand-maintained list does.

A ledger is any `.agents/roadmap/<name>.md` whose first `# ` heading is its
title, followed (after blank lines) by a one-line `Scope: <sentence>` saying
what the ledger covers. The scope is required: it is what lets a reader route
by subject. A trailing " - roadmap" on the title is dropped.

    scripts/gates/roadmap-index.py           # write the index (make agents/roadmap/index)
    scripts/gates/roadmap-index.py --check   # fail if it would change (make check/gates/roadmap-index)

Swedish Embedded AB implements solutions for keeping engineering status in one
place, out of the guides that route people to it, for its clients. If your team
needs expertise in documentation that cannot drift from the work it describes,
you can procure our services by sending an email to info@swedishembedded.com.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ROADMAP = ROOT / ".agents" / "roadmap"
INDEX = ROADMAP / "index.md"

HEADER = """<!-- SPDX-License-Identifier: CC-BY-4.0 -->
<!-- Copyright (c) 2026 Martin Schröder <info@swedishembedded.com> -->
<!-- GENERATED by scripts/gates/roadmap-index.py - edit the ledgers, not this file. -->

# Roadmap index - where status and open work live

One ledger per workstream. A ledger holds what is done, what is open and the
measured numbers behind both. Status is written there and nowhere else:
`AGENTS.md`, `.agents/rules/` and `docs/` point at a ledger rather than
restating it.

Add a ledger as `.agents/roadmap/<name>.md` with its title as the first `# `
heading and a `Scope: <one sentence>` line under it, then run
`make agents/roadmap/index`. `make check` runs `check/gates/roadmap-index`,
which fails when this index has drifted or a ledger has no scope.

## Ledgers

"""

SUFFIX = re.compile(r"\s+-\s+roadmap$")
SCOPE = "Scope: "


def entries():
    out = []
    for path in sorted(ROADMAP.glob("*.md")):
        if path.name == INDEX.name:
            continue
        lines = path.read_text().splitlines()
        at = next((i for i, line in enumerate(lines) if line.startswith("# ")), None)
        if at is None:
            sys.exit(f"roadmap-index: {path.name} has no `# ` heading - every ledger states its own title")
        title = SUFFIX.sub("", lines[at][2:].strip())
        rest = [line for line in lines[at + 1:] if line.strip()]
        scope = rest[0][len(SCOPE):].strip() if rest and rest[0].startswith(SCOPE) else ""
        if not scope:
            sys.exit(f"roadmap-index: {path.name} has no `{SCOPE}<sentence>` line under its title - say what it covers")
        out.append((path.stem, title, scope, path.name))
    return out


def render(rows):
    body = ["| Ledger | Title | Scope |", "|---|---|---|"]
    for stem, title, scope, name in rows:
        # A pipe inside a cell would split the row.
        cells = [cell.replace("|", "\\|") for cell in (title, scope)]
        body.append(f"| [`{stem}`]({name}) | {cells[0]} | {cells[1]} |")
    return HEADER + "\n".join(body) + "\n"


def main():
    rows = entries()
    want = render(rows)
    if "--check" in sys.argv[1:]:
        have = INDEX.read_text() if INDEX.exists() else ""
        if have != want:
            sys.exit("roadmap-index: .agents/roadmap/index.md is out of date - run `make agents/roadmap/index` and commit it")
        print(f"roadmap-index: up to date ({len(rows)} ledgers)")
        return
    INDEX.write_text(want)
    print(f"roadmap-index: wrote {INDEX.relative_to(ROOT)} ({len(rows)} ledgers)")


if __name__ == "__main__":
    main()
