"""External reference fixtures: build the pinned oracle environment, freeze fixtures, and prove they still hold.

    python3 -I scripts/conformance/external.py env                       # target/validation/venv from the lock
    python3 -I scripts/conformance/external.py generate ORACLE.py        # run an oracle, freeze its fixture
    python3 -I scripts/conformance/external.py check                     # every fixture, reference and oracle
    python3 -I scripts/conformance/external.py differential NAME --seed 7 --cases 500

An oracle (validation/oracles/<area>/<name>.py) runs pinned external references and writes one JSON fixture:
`{"fixture": NAME, "references": [ids], "cases": [...]}`, deterministically (same bytes for the same environment).
`generate` runs it and records in validation/fixtures.yaml the fixture's digest, the oracle's digest, the
references it ran and the test that consumes it; the fixture is then reviewed and committed, never regenerated by
a test. `check` refuses: an oracle environment whose packages are not the lock's (a wrong reference revision), a
fixture or oracle whose bytes are not the ones recorded, a reference the lock does not pin, an oracle that crashes,
and a fixture its oracle no longer writes byte for byte. `differential` has the oracle draw fresh cases
(`--seed`, `--cases`; the fixture then says `"differential": true`) and runs the consuming Rust test against them
through SPLINTER_FIXTURE_DIR, so Splinter and the reference meet on inputs neither has seen.

Paths are relative to --root (the repository, by default), so the runner's own specification
(scripts/conformance/test_external.py) runs it against scratch repositories.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

LOCK = "validation/references.lock.yaml"
MANIFEST = "validation/fixtures.yaml"
MANIFEST_SCHEMA = "splinter.validation-fixtures/v1"
LOCK_SCHEMA = "splinter.validation-references/v1"
VENV = "target/validation/venv"
OVERRIDE_VAR = "SPLINTER_FIXTURE_DIR"


class Refused(Exception):
    """A check that did not hold, with what to do about it."""


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# The lock and manifest are YAML; the runner itself runs on the system Python, which has no YAML parser, so it reads
# them through the oracle environment's (pinned) PyYAML, or the system's when the environment is being built.
def load_yaml(python: str, path: Path) -> dict:
    out = subprocess.run([python, "-I", "-c", "import json,sys,yaml; json.dump(yaml.safe_load(open(sys.argv[1])), "
                          "sys.stdout)", str(path)], capture_output=True, text=True, check=False)
    if out.returncode != 0:
        raise Refused(f"{path}: {out.stderr.strip() or 'does not parse'}")
    return json.loads(out.stdout) or {}


def dump_manifest(path: Path, fixtures: dict) -> None:
    lines = ["# SPDX-License-Identifier: Apache-2.0",
             "# Copyright (c) 2026 Martin Schröder <info@swedishembedded.com>",
             "#",
             "# The frozen reference fixtures: written by scripts/conformance/external.py generate, checked by its",
             "# `check` and, digest by digest, by every test that reads one (crates/conformance).",
             f"schema: {MANIFEST_SCHEMA}", "fixtures:"]
    for name in sorted(fixtures):
        entry = fixtures[name]
        lines.append(f"  {name}:")
        for key in ("path", "sha256", "oracle", "oracle_sha256"):
            lines.append(f"    {key}: {json.dumps(str(entry[key]))}")
        lines.append(f"    references: {json.dumps(entry['references'])}")
        lines.append(f"    test: {json.dumps(entry['test'])}")
    path.write_text("\n".join(lines) + "\n")


class Repo:
    def __init__(self, root: Path, python: str | None):
        self.root = root
        self.python = python or str(root / VENV / "bin" / "python")

    def lock(self) -> dict:
        lock = load_yaml(self.python, self.root / LOCK)
        if lock.get("schema") != LOCK_SCHEMA:
            raise Refused(f"{LOCK}: not a {LOCK_SCHEMA} file")
        return lock

    def manifest(self) -> dict:
        path = self.root / MANIFEST
        if not path.exists():
            return {}
        manifest = load_yaml(self.python, path)
        if manifest.get("schema") != MANIFEST_SCHEMA:
            raise Refused(f"{MANIFEST}: not a {MANIFEST_SCHEMA} file")
        return manifest.get("fixtures") or {}

    def installed(self) -> dict[str, str]:
        out = subprocess.run([self.python, "-I", "-c", "import json; from importlib.metadata import distributions as d; "
                              "print(json.dumps({x.metadata['Name'].lower().replace('_', '-'): x.version for x in d()}))"],
                             capture_output=True, text=True, check=False)
        if out.returncode != 0:
            raise Refused(f"no oracle environment at {self.python} (run `external.py env`)")
        return json.loads(out.stdout)

    def check_environment(self, lock: dict) -> None:
        installed = self.installed()
        for package in lock["packages"]:
            found = installed.get(package["name"])
            if found != str(package["version"]):
                raise Refused(f"reference {package['name']}: the oracle environment has {found or 'none'}, the lock "
                              f"pins {package['version']} (rebuild it with `external.py env`)")

    def run_oracle(self, oracle: Path, out: Path, extra: list[str]) -> dict:
        ran = subprocess.run([self.python, "-I", str(self.root / oracle), "--out", str(out), *extra],
                             cwd=self.root, capture_output=True, text=True, check=False)
        if ran.returncode != 0:
            raise Refused(f"oracle {oracle} failed (exit {ran.returncode}): {ran.stderr.strip()[-2000:]}")
        try:
            written = json.loads(out.read_text())
        except (OSError, ValueError) as e:
            raise Refused(f"oracle {oracle} wrote no JSON fixture: {e}") from e
        if not isinstance(written.get("fixture"), str) or not written.get("cases"):
            raise Refused(f"oracle {oracle}: a fixture names itself and holds cases")
        return written


def fixture_path(name: str) -> str:
    return f"validation/fixtures/{name}.json"


def cmd_env(repo: Repo, _args) -> None:
    lock = load_yaml(sys.executable if _has_yaml(sys.executable) else repo.python, repo.root / LOCK)
    venv = repo.root / VENV
    subprocess.run([sys.executable, "-m", "venv", "--clear", str(venv)], check=True)
    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False) as req:
        for p in lock["packages"]:
            req.write(f"{p['name']}=={p['version']} --hash=sha256:{p['sha256']}\n")
    subprocess.run([str(venv / "bin" / "pip"), "install", "-q", "--no-deps", "--require-hashes", "-r", req.name],
                   check=True)
    os.unlink(req.name)
    print(f"external: oracle environment {venv} built from {LOCK}", file=sys.stderr)


def _has_yaml(python: str) -> bool:
    return subprocess.run([python, "-I", "-c", "import yaml"], capture_output=True, check=False).returncode == 0


def cmd_generate(repo: Repo, args) -> None:
    lock = repo.lock()
    repo.check_environment(lock)
    oracle = Path(args.oracle)
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "fixture.json"
        written = repo.run_oracle(oracle, out, [])
        name = written["fixture"]
        unknown = [r for r in written.get("references", []) if r not in lock["references"]]
        if unknown:
            raise Refused(f"oracle {oracle} ran references the lock does not pin: {unknown}")
        target = repo.root / fixture_path(name)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(out.read_bytes())
    fixtures = repo.manifest()
    fixtures[name] = {
        "path": fixture_path(name),
        "sha256": sha256(target),
        "oracle": str(oracle),
        "oracle_sha256": sha256(repo.root / oracle),
        "references": written.get("references", []),
        "test": args.test or fixtures.get(name, {}).get("test") or "",
    }
    if not fixtures[name]["test"]:
        raise Refused(f"fixture {name}: name the test that reads it (--test package/target/filter)")
    dump_manifest(repo.root / MANIFEST, fixtures)
    print(f"external: froze {fixture_path(name)} ({len(written['cases'])} cases); review the diff", file=sys.stderr)


def cmd_check(repo: Repo, _args) -> None:
    lock = repo.lock()
    repo.check_environment(lock)
    fixtures = repo.manifest()
    if not fixtures:
        raise Refused(f"{MANIFEST} lists no fixture: a check of nothing certifies nothing")
    for name, entry in sorted(fixtures.items()):
        path, oracle = repo.root / entry["path"], Path(entry["oracle"])
        if not path.is_file():
            raise Refused(f"fixture {name}: {entry['path']} is missing")
        if sha256(path) != entry["sha256"]:
            raise Refused(f"fixture {name}: {entry['path']} is not the file recorded (an edited expected value?)")
        if not (repo.root / oracle).is_file() or sha256(repo.root / oracle) != entry["oracle_sha256"]:
            raise Refused(f"fixture {name}: its oracle {oracle} changed since the fixture was frozen (regenerate)")
        unknown = [r for r in entry["references"] if r not in lock["references"]]
        if unknown:
            raise Refused(f"fixture {name}: references {unknown} are not pinned in {LOCK}")
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp) / "fixture.json"
            repo.run_oracle(oracle, out, [])
            if out.read_bytes() != path.read_bytes():
                raise Refused(f"fixture {name}: the pinned references no longer write it byte for byte")
        print(f"external: {name} holds ({entry['references']})", file=sys.stderr)


def cmd_differential(repo: Repo, args) -> None:
    lock = repo.lock()
    repo.check_environment(lock)
    entry = repo.manifest().get(args.name)
    if entry is None:
        raise Refused(f"fixture {args.name} is not listed in {MANIFEST}")
    package, target, test_filter = entry["test"].split("/", 2)
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / (args.name.replace("/", "_") + ".json")
        written = repo.run_oracle(Path(entry["oracle"]), out,
                                  ["--seed", str(args.seed), "--cases", str(args.cases)])
        if written.get("differential") is not True or written["fixture"] != args.name:
            raise Refused(f"oracle {entry['oracle']} did not draw {args.name} (a draw says `differential`)")
        selector = ["--lib"] if target == "lib" else ["--test", target]
        ran = subprocess.run([args.cargo, "test", "--release", "-q", "-p", package, *selector, "--", test_filter],
                             cwd=repo.root, env={**os.environ, OVERRIDE_VAR: tmp}, check=False)
        if ran.returncode != 0:
            raise Refused(f"differential {args.name} (seed {args.seed}): Splinter disagrees with the reference; "
                          f"rerun with the same seed to reproduce")
    print(f"external: differential {args.name} seed {args.seed}, {len(written['cases'])} cases agree",
          file=sys.stderr)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--python", help="the oracle environment's interpreter (default: the repository's venv)")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("env")
    generate = sub.add_parser("generate")
    generate.add_argument("oracle")
    generate.add_argument("--test", help="the consuming test, package/target/filter")
    sub.add_parser("check")
    differential = sub.add_parser("differential")
    differential.add_argument("name")
    differential.add_argument("--seed", type=int, required=True)
    differential.add_argument("--cases", type=int, default=200)
    differential.add_argument("--cargo", default="cargo")
    args = parser.parse_args()
    repo = Repo(args.root.resolve(), args.python)
    try:
        {"env": cmd_env, "generate": cmd_generate, "check": cmd_check, "differential": cmd_differential}[
            args.command](repo, args)
    except Refused as refused:
        print(f"external: {refused}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
