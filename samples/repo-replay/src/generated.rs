//! Generated and vendored paths.
//!
//! A lock file, a vendored dependency or a protobuf stub is not something a
//! person describes in a task and an agent edits by hand; reproducing it
//! teaches nothing and its bytes cannot be derived from the task. Such paths
//! are left out of the task's diff, out of the exact-tree gate and out of the
//! "every changed file was edited" rule. A commit that is mostly generated is
//! skipped, counted under its own reason.
//!
//! The project's own generator is not run (that would execute the history's
//! code on the host); the paths are excluded instead.

/// Directory names whose whole subtree is generated, vendored or a build
/// artifact.
const GENERATED_DIRS: &[&str] = &[
    "vendor",
    "node_modules",
    "third_party",
    "dist",
    "build",
    "target",
    "__pycache__",
    ".pytest_cache",
    ".mypy_cache",
    ".venv",
    ".git",
    // The agent runtime's own state (its audit log), written into the working directory.
    ".sven",
];

/// File names that are generated by a package manager.
const GENERATED_FILES: &[&str] = &[
    "Cargo.lock",
    "package-lock.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "poetry.lock",
    "Pipfile.lock",
    "go.sum",
    "Gemfile.lock",
    "composer.lock",
];

/// File name suffixes of generated output.
const GENERATED_SUFFIXES: &[&str] = &[
    ".min.js",
    ".min.css",
    ".map",
    ".pb.go",
    "_pb2.py",
    ".pyc",
    ".generated.rs",
    ".generated.ts",
];

/// Header text that marks a file as generated when it is in the first lines.
const GENERATED_MARKERS: &[&str] = &["@generated", "Code generated", "DO NOT EDIT"];

/// Whether `path` (repository-relative, `/`-separated) is generated or
/// vendored by its name alone.
#[must_use]
pub fn is_generated_path(path: &str) -> bool {
    let mut parts = path.split('/').peekable();
    while let Some(part) = parts.next() {
        let is_last = parts.peek().is_none();
        if !is_last && GENERATED_DIRS.contains(&part) {
            return true;
        }
        if is_last
            && (GENERATED_FILES.contains(&part)
                || GENERATED_SUFFIXES.iter().any(|s| part.ends_with(s)))
        {
            return true;
        }
    }
    false
}

/// Whether the start of `content` declares the file generated.
#[must_use]
pub fn has_generated_header(content: &str) -> bool {
    content
        .lines()
        .take(5)
        .any(|line| GENERATED_MARKERS.iter().any(|m| line.contains(m)))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_decide() {
        assert!(is_generated_path("Cargo.lock"));
        assert!(is_generated_path("web/package-lock.json"));
        assert!(is_generated_path("vendor/lib/a.c"));
        assert!(is_generated_path("static/app.min.js"));
        assert!(!is_generated_path("src/vendor.rs"));
        assert!(!is_generated_path("src/build.rs"));
        assert!(!is_generated_path("build"));
    }

    #[test]
    fn header_decides() {
        assert!(has_generated_header(
            "// Code generated by protoc. DO NOT EDIT.\npackage x"
        ));
        assert!(!has_generated_header("fn main() {}\n"));
    }
}
