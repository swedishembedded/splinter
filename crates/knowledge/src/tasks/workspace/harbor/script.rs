//! The scripts of the interchange: the runner that stands in for a Harbor
//! verifier on the host, and the verifier script an export gives Harbor.
//!
//! Harbor runs `tests/test.sh` in a container where the tests are at
//! `/tests`, the verifier's logs at `/logs/verifier` and the task's files at
//! its working directory, and takes the verdict from `reward.txt` or
//! `reward.json` there. On the host those paths do not exist, so the
//! imported check rewrites them, at run time and only where they stand as
//! whole paths, to the tree, a private tests copy and a private logs
//! directory, then reads the reward the way Harbor's verifier does. A task
//! passes only when its `reward` is exactly 1: partial credit is not a pass.

/// The tree-relative directory the imported check lives in; hidden from the
/// solver and protected from its change.
pub(super) const HIDDEN_DIR: &str = ".harbor";

/// The placeholders a script's container paths are rewritten to.
const LOGS: &str = "@@LOGS@@";
const TESTS: &str = "@@TESTS@@";
const WORKDIR: &str = "@@WORKDIR@@";

/// Whether `c` can continue a path word, so that a match followed or
/// preceded by it is a different path (`/tests` in `/testsuite`, `/app` in
/// `/usr/app`).
fn path_char(c: char) -> bool {
    c.is_ascii_alphanumeric() || matches!(c, '_' | '.' | '-' | '/')
}

/// `text` with each whole-path occurrence of `path` replaced by `with`.
pub(super) fn replace_path(text: &str, path: &str, with: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    let mut before: Option<char> = None;
    while let Some(at) = rest.find(path) {
        let head = &rest[..at];
        let prev = head.chars().last().or(before);
        let tail = &rest[at + path.len()..];
        let next = tail.chars().next();
        let whole = prev.is_none_or(|c| !path_char(c))
            && next.is_none_or(|c| !(c.is_ascii_alphanumeric() || matches!(c, '_' | '-' | '.')));
        out.push_str(head);
        out.push_str(if whole { with } else { path });
        before = path.chars().last();
        rest = tail;
    }
    out.push_str(rest);
    out
}

/// `script` with the container paths of Harbor's verifier as placeholders.
pub(super) fn placeholders(script: &str, workdir: &str) -> String {
    let logged = replace_path(script, "/logs/verifier", LOGS);
    let tested = replace_path(&logged, "/tests", TESTS);
    replace_path(&tested, workdir.trim_end_matches('/'), WORKDIR)
}

/// The runner that grades a tree the way Harbor's verifier would. Its first
/// argument is nothing; it finds its tests beside itself.
pub(super) fn runner() -> String {
    format!(
        r#"#!/bin/sh
# Generated by splinter from a Harbor task's tests/: runs the task's own
# verifier script on this tree and exits 0 only when its reward is exactly 1.
set -u
HERE=$(cd "$(dirname "$0")" && pwd)
TREE=$(dirname "$HERE")
LOGS=$(mktemp -d "${{TMPDIR:-/tmp}}/harbor-verifier.XXXXXX") || exit 2
H_TREE="$TREE"; H_LOGS="$LOGS"; H_TESTS="$LOGS/tests"
export H_TREE H_LOGS H_TESTS
cp -R "$HERE/tests" "$H_TESTS" || exit 2
rewrite() {{
  awk '{{ gsub("{logs}", ENVIRON["H_LOGS"]); gsub("{tests}", ENVIRON["H_TESTS"]); gsub("{workdir}", ENVIRON["H_TREE"]); print }}' "$1" > "$1.rewritten" &&
    cat "$1.rewritten" > "$1" && rm -f "$1.rewritten"
}}
find "$H_TESTS" -type f | while IFS= read -r file; do
  if grep -Iq . "$file" 2>/dev/null; then rewrite "$file"; fi
done
chmod +x "$H_TESTS/test.sh" 2>/dev/null
cd "$TREE" || exit 2
"$H_TESTS/test.sh" > "$LOGS/stdout.txt" 2>&1
if [ -f "$LOGS/reward.json" ]; then
  grep -Eq '"reward"[[:space:]]*:[[:space:]]*1(\.0*)?[[:space:]]*[,}}]' "$LOGS/reward.json"
  verdict=$?
elif [ -f "$LOGS/reward.txt" ]; then
  awk 'NR == 1 {{ exit !($1 + 0 == 1) }}' "$LOGS/reward.txt"
  verdict=$?
else
  echo "the verifier wrote no reward" >&2
  verdict=1
fi
if [ "$verdict" -ne 0 ]; then tail -n 40 "$LOGS/stdout.txt" >&2; fi
rm -rf "$LOGS"
exit "$verdict"
"#,
        logs = LOGS,
        tests = TESTS,
        workdir = WORKDIR,
    )
}

/// The wrapper that runs a Harbor `solution/solve.sh` in a tree: `/solution`
/// and the working directory are rewritten to the tree's own. It runs from
/// the tree's root, with the script and the solution's files beside it.
pub(super) fn oracle_runner() -> String {
    r#"#!/bin/sh
# Generated by splinter: runs a Harbor task's solution/solve.sh on this tree.
set -u
TREE=$(pwd)
H_TREE="$TREE"; H_SOLUTION="$TREE/.oracle/solution"
export H_TREE H_SOLUTION
awk '{ gsub("@@SOLUTION@@", ENVIRON["H_SOLUTION"]); gsub("@@WORKDIR@@", ENVIRON["H_TREE"]); print }' .oracle/solve.sh > .oracle/solve.rewritten.sh || exit 2
chmod +x .oracle/solve.rewritten.sh
exec ./.oracle/solve.rewritten.sh
"#
    .to_string()
}

/// The oracle script with its container paths as placeholders.
pub(super) fn oracle_placeholders(script: &str, workdir: &str) -> String {
    let solved = replace_path(script, "/solution", "@@SOLUTION@@");
    replace_path(&solved, workdir.trim_end_matches('/'), WORKDIR)
}

/// `word` quoted for a POSIX shell.
fn quote(word: &str) -> String {
    format!("'{}'", word.replace('\'', r"'\''"))
}

/// The `tests/test.sh` an export gives Harbor: it lays the hidden overlay
/// over the working directory, runs each command and writes the reward. The
/// commands are the check's own, as argv.
pub(super) fn verifier(
    workdir: &str,
    fail_to_pass: &[Vec<String>],
    pass_to_pass: &[Vec<String>],
) -> String {
    let mut text = String::from(
        "#!/bin/sh\n# Generated by splinter. Lays the hidden files over the working directory,\n# runs the task's commands and writes the reward Harbor reads.\nset -u\n",
    );
    text.push_str(&format!("cd {} || exit 1\n", quote(workdir)));
    text.push_str("[ -d /tests/overlay ] && cp -R /tests/overlay/. .\nstatus=0\n");
    for argv in fail_to_pass.iter().chain(pass_to_pass) {
        let words: Vec<String> = argv.iter().map(|w| quote(w)).collect();
        text.push_str(&format!("{} || status=1\n", words.join(" ")));
    }
    text.push_str(
        "mkdir -p /logs/verifier\nif [ \"$status\" -eq 0 ]; then echo 1 > /logs/verifier/reward.txt; else echo 0 > /logs/verifier/reward.txt; fi\n",
    );
    text
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_whole_paths_are_rewritten() {
        let script = "cd /app && pytest /tests/test_x.py --rootdir=/app/src; cat /usr/app/x /testsuite /app2 > /logs/verifier/reward.txt";
        let out = placeholders(script, "/app");
        assert_eq!(
            out,
            "cd @@WORKDIR@@ && pytest @@TESTS@@/test_x.py --rootdir=@@WORKDIR@@/src; cat /usr/app/x /testsuite /app2 > @@LOGS@@/reward.txt"
        );
    }

    #[test]
    fn a_verifier_for_harbor_quotes_every_word_of_every_command() {
        let text = verifier(
            "/app",
            &[vec!["python3".into(), "-c".into(), "print('x y')".into()]],
            &[],
        );
        assert!(
            text.contains(r"'python3' '-c' 'print('\''x y'\'')' || status=1"),
            "{text}"
        );
        assert!(text.contains("cd '/app'"));
    }
}
