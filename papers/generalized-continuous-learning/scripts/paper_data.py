"""The tables and figure data of the paper, made from its data/ directory into OUT (the build's generated/ directory):
the examiner's signed group verdict of the Lua run (data/rsi5-groups-G.json) and a copy of the aggregate files of the private
evidence dataset swedishembedded/source-to-transfer-evidence (data/vim-transfer/: evaluation/aggregates.json,
decision/*.json, material/funnel.json).

usage: paper_data.py DATA_DIR OUT_DIR"""

from __future__ import annotations

import csv
import json
import math
import os
import sys

ARMS = ["b", "c", "d", "f", "g"]
# The arms by their training material; the registration's letters stay in the appendix and the evidence's file names.
LABEL = {"b": "all verified", "c": "one per task", "d": "productive actions", "f": "shuffled requests",
         "g": "outcome first", "s": "student only"}
Z = 1.959963984540054


def wilson(k: int, n: int) -> tuple[float, float]:
    """95% Wilson score interval of a binomial proportion k/n."""
    if n == 0:
        return (math.nan, math.nan)
    p = k / n
    d = 1 + Z * Z / n
    c = (p + Z * Z / (2 * n)) / d
    h = Z * math.sqrt(p * (1 - p) / n + Z * Z / (4 * n * n)) / d
    return (0.0 if k == 0 else max(0.0, c - h), min(1.0, c + h))


def write_csv(path: str, header: list[str], rows: list[list]) -> None:
    with open(path, "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        for r in rows:
            w.writerow([f"{v:.6g}" if isinstance(v, float) else v for v in r])


def fmt_p(p: float) -> str:
    if p < 1e-4:
        m, e = f"{p:.1e}".split("e")
        return f"${m}\\times 10^{{{int(e)}}}$"
    return f"{p:.2g}" if p < 0.01 else f"{p:.3f}".rstrip("0")


def main(data: str, out: str) -> None:
    ev = os.path.join(data, "vim-transfer")
    agg = json.load(open(os.path.join(ev, "evaluation", "aggregates.json")))["arm_seeds"]
    dec = json.load(open(os.path.join(ev, "decision", "decision-eval-exam.json")))
    sec = json.load(open(os.path.join(ev, "decision", "secondary-eval-exam.json")))
    funnel = json.load(open(os.path.join(ev, "material", "funnel.json")))
    os.makedirs(out, exist_ok=True)

    table = []
    for a in ARMS:
        s = dec["arms"][a]
        pr = dec["primary"].get(a)
        vf = dec["vs_control"].get(a)
        rows = [r for r in agg if r["arm"] == a]
        comp = rows[0]["composition"]
        per_seed = ", ".join(str(r["eval-exam"]["candidate"]["passed"]) for r in sorted(rows, key=lambda r: r["seed"]))
        cell = lambda r, holm: (f"{r['wins']}/{r['losses']}, {fmt_p(r['p'])}" + ("" if not holm else
                                ("" if r["significant_holm"] else " (n.s.)"))) if r else "--"
        table.append(f"{LABEL[a]} & {comp['train_records']} & {s['passes']} ({per_seed}) & "
                     f"{s['tasks_solved']} & {s['base_passes']}/{s['base_attempts']} & {cell(pr, True)} & "
                     f"{cell(vf, False)} \\\\")
    open(os.path.join(out, "vim-transfer-table.tex"), "w").write(
        "% Generated by scripts/paper_data.py from data/; do not edit.\n" + "\n".join(table) + "\n")

    sec_rows = []
    for k, r in sec["secondary"].items():
        x, y = k.split("-vs-")
        sec_rows.append(f"{LABEL[x]} vs {LABEL[y]} & {r['wins']}/{r['losses']} & {fmt_p(r['p_two_sided'])} & "
                        f"${r['diff']:+.3f}$ [${r['ci95'][0]:+.3f}$, ${r['ci95'][1]:+.3f}$] \\\\")
    open(os.path.join(out, "vim-transfer-secondary.tex"), "w").write(
        "% Generated by scripts/paper_data.py from data/; do not edit.\n" + "\n".join(sec_rows) + "\n")

    # T1, the held-out authored tasks (secondary): every arm whose three seeds have been measured.
    t1_dec = json.load(open(os.path.join(ev, "decision", "decision-eval-unseen.json")))
    t1_sec = json.load(open(os.path.join(ev, "decision", "secondary-eval-unseen.json")))
    t1 = []
    for a in ARMS:
        if a not in t1_dec["arms"]:
            part = os.path.join(ev, "decision", f"per-seed-eval-unseen-{a}.json")
            if not os.path.isfile(part):
                t1.append(f"{LABEL[a]} & \\multicolumn{{5}}{{l}}{{not yet measured}} \\\\")
                continue
            seeds = json.load(open(part))["per_seed"]
            c = sum(v["candidate"]["passes"] for v in seeds.values()); n = sum(v["candidate"]["attempts"] for v in seeds.values())
            bc = sum(v["baseline"]["passes"] for v in seeds.values()); bn = sum(v["baseline"]["attempts"] for v in seeds.values())
            t1.append(f"{LABEL[a]} ({len(seeds)} of 3 seeds) & 94 & {c}/{n} ({c / n:.3f}) & {bc}/{bn} & "
                      f"\\multicolumn{{2}}{{l}}{{no test until all three seeds are measured}} \\\\")
            continue
        s1 = t1_dec["arms"][a]
        r = t1_dec["primary"].get(a) or t1_sec["exploratory"]["f-vs-base"]
        test = (f"{r['wins']}/{r['losses']}, {fmt_p(r['p'])}" if a in t1_dec["primary"] else
                f"{r['wins']}/{r['losses']}, {fmt_p(r['p_two_sided'])} (two-sided)")
        t1.append(f"{LABEL[a]} & {r['tasks']} & {s1['passes']}/{s1['attempts']} ({s1['pass_rate']:.3f}) & "
                  f"{s1['base_passes']}/{s1['base_attempts']} & {test} & "
                  f"${r['diff']:+.3f}$ [${r['ci95'][0]:+.3f}$, ${r['ci95'][1]:+.3f}$] \\\\")
    open(os.path.join(out, "vim-transfer-t1.tex"), "w").write(
        "% Generated by scripts/paper_data.py from data/; do not edit.\n" + "\n".join(t1) + "\n")

    # The Lua run's generations on its sealed exam: the share of items right per lineage and the mean, from the
    # examiner's group verdict.
    lua = json.load(open(os.path.join(data, "rsi5-groups-G.json")))["groups"]
    rows = []
    for g, name in enumerate(["base", "gen1", "gen2", "gen3", "gen4"]):
        grp = lua[name]
        for i, share in enumerate(grp["shares"]):
            rows.append([g, i, share, grp["share"]])
    write_csv(os.path.join(out, "lua-generations.csv"), ["generation", "lineage", "share", "mean"], rows)

    # (e) the authoring funnel.
    fw, bw = funnel["forward"], funnel["backward"]
    st = fw["stages"]
    fwd = [["sections", st["sections"]["items"]],
           ["proposal sets", st["proposed"]["items"] + st["proposed-b"]["items"] + st["proposed-c"]["items"]],
           ["candidate tasks", fw["admission"]["candidates"]],
           ["admitted", fw["admission"]["admitted"]],
           ["oracle solved", fw["attempts"]["oracle"]["tasks_solved"]],
           ["teacher solved", fw["attempts"]["teacher-attempts"]["tasks_solved"]],
           ["student solved", fw["attempts"]["student-attempts"]["tasks_solved"]]]
    bst = bw["stages"]
    bwd = [["sections", bst["sections"]["items"]],
           ["proposal sets", bst["proposed"]["items"]],
           ["candidate tasks", bw["proposals"]["proposed"]],
           ["to reproduce", bw["proposals"]["admitted"]],
           ["reached", bw["attempts"]["reproduce-attempts"]["tasks_solved"]],
           ["replayable", bst["describe-items"]["items"]],
           ["admitted", bw["admission"]["admitted"]],
           ["oracle solved", bw["attempts"]["oracle"]["tasks_solved"]],
           ["teacher solved", bw["attempts"]["teacher-attempts"]["tasks_solved"]],
           ["student solved", bw["attempts"]["student-attempts"]["tasks_solved"]]]
    for name, rows in (("forward", fwd), ("backward", bwd)):
        write_csv(os.path.join(out, f"vim-transfer-funnel-{name}.csv"), ["step", "y", "count"],
                  [[s, len(rows) - i, c] for i, (s, c) in enumerate(rows)])
    rates = []
    for name, f, stages in (("forward", fw, ("student-attempts", "teacher-attempts")),
                            ("backward", bw, ("student-attempts", "teacher-attempts"))):
        for s in stages:
            a = f["attempts"][s]
            rates.append([name, s.split("-")[0], a["counted"], a["passed"], a["pass_rate"], a["tasks"], a["tasks_solved"]])
    model = {"student": "Qwen3-4B", "teacher": "Qwen3.8-27B-FP8"}
    mode = {"forward": "section by section", "backward": "outcome first"}
    open(os.path.join(out, "vim-transfer-attempts.tex"), "w").write(
        "% Generated by scripts/paper_data.py from data/; do not edit.\n" + "\n".join(
            f"{mode[m]} & {model[w]} & {n} & {r:.3f} & {t} & {sv} \\\\" for m, w, n, _, r, t, sv in rates) + "\n")


    # Exams and held-out authored tasks per arm and seed, each with its paired base, for the headline figure.
    for name, source in (("exam", sec), ("t1", t1_sec)):
        rows = []
        for fork, r in sorted(source["per_seed"].items()):
            _, a, seed = fork.split("-")
            for side in ("candidate", "baseline"):
                k, n = r[side]["passes"], r[side]["attempts"]
                lo, hi = wilson(k, n)
                x = ARMS.index(a) + 1 + (int(seed[1:]) - 2) * 0.2
                rows.append([LABEL[a], int(seed[1:]), side, x, k, n, k / n, lo, hi])
        write_csv(os.path.join(out, f"vim-transfer-{name}-seeds.csv"),
                  ["arm", "seed", "side", "x", "passes", "attempts", "rate", "lo", "hi"], rows)
    pooled = []
    for name, d, sd in (("exam", dec, sec), ("t1", t1_dec, t1_sec)):
        for a in ARMS:
            if a in d["arms"]:
                # the registered comparison with the base, or for the control its exploratory one
                r = d["primary"].get(a) or sd.get("exploratory", {}).get(f"{a}-vs-base")
                rate = d["arms"][a]["pass_rate"]
                lo, hi = r["ci95"]
                base = d["arms"][a]["base_passes"] / d["arms"][a]["base_attempts"]
                pooled.append([name, LABEL[a], ARMS.index(a) + 1, rate, base, max(0.0, base + lo), base + hi])  # a rate is >= 0
    write_csv(os.path.join(out, "vim-transfer-pooled.csv"), ["eval", "arm", "x", "rate", "base", "lo", "hi"], pooled)

    # The Lua run's registered comparisons with the examiner's 95% intervals (percentage points).
    comp = json.load(open(os.path.join(data, "rsi5-groups-G.json")))["comparisons"]
    steps = [("1 vs base", comp["step1"]), ("2 vs 1", comp["step2"]), ("3 vs 2", comp["step3"]), ("4 vs 3", comp["step4"]),
             ("4 vs base", comp["gen4-over-base"]), ("new families", comp["gen4-over-base"]["strata"]["family_set:v2"])]
    write_csv(os.path.join(out, "lua-steps.csv"), ["x", "label", "diff", "lo", "hi", "holds"],
              [[i + 1, lab, 100 * c["difference"], 100 * c["interval"][0], 100 * c["interval"][1],
                1 if c["interval"][0] > 0 else 0] for i, (lab, c) in enumerate(steps)])

    # The Vim generation-1 gain over the paired base per arm, with the task-bootstrap interval (percentage points).
    gain = []
    for a in ARMS:
        pr = dec["primary"].get(a)
        s1 = dec["arms"][a]
        diff = 100 * (pr["diff"] if pr else s1["pass_rate"])
        lo, hi = ((100 * pr["ci95"][0], 100 * pr["ci95"][1]) if pr else (diff, diff))
        gain.append([ARMS.index(a) + 1, LABEL[a], diff, lo, hi, 1 if pr else 0])
    write_csv(os.path.join(out, "vim-gain.csv"), ["x", "arm", "diff", "lo", "hi", "registered"], gain)

    # Training records by the model that made them (train split), per arm.
    # ... with each arm's pooled exam pass rate and the task-bootstrap interval of its difference from the paired base;
    # the student-only arm was decided on its own (decision/student-only-*), outside the registered family.
    only = json.load(open(os.path.join(ev, "decision", "student-only-decision-eval-exam.json")))
    rec = []
    for i, a in enumerate(ARMS + ["s"]):
        bym = next(r for r in agg if r["arm"] == a)["records_by_model"]
        d = only if a == "s" else dec
        r = d["primary"].get(a)
        rate = d["arms"][a]["pass_rate"]
        lo, hi = (r["ci95"] if r else (0.0, 0.0))
        rec.append([i + 1, LABEL[a], bym.get("train:Qwen/Qwen3.8-27B-FP8", 0), bym.get("train:Qwen/Qwen3-4B", 0),
                    100 * rate, 100 * max(0.0, lo), 100 * hi, d["arms"][a]["passes"], d["arms"][a]["attempts"]])
    write_csv(os.path.join(out, "vim-records.csv"),
              ["y", "arm", "teacher", "student", "exam_pct", "lo_pct", "hi_pct", "passes", "attempts"], rec)

    # The headline: exam pass rate per generation of the loop, per model size, with Wilson intervals over attempts, and
    # the teacher's level for reference.
    loop = json.load(open(os.path.join(ev, "loop", "loop.json")))
    lrows = []
    for size, gens in loop["sizes"].items():
        g0 = gens[0]
        for g, k, n in [(0, g0["base_passes"], g0["base_attempts"])] + [(e["generation"], e["passes"], e["attempts"]) for e in gens]:
            lo, hi = wilson(k, n)
            lrows.append([size, g, k, n, 100 * k / n, 100 * lo, 100 * hi])
    write_csv(os.path.join(out, "loop.csv"), ["size", "generation", "passes", "attempts", "pct", "lo", "hi"], lrows)
    teacher = loop["teacher_exam"]
    g1 = loop["sizes"]["4B"][0]
    s_only = only["arms"]["s"]

    # Appendix tables: every dataset, model and evidence repository with its pinned revision, and the builds.
    tex = lambda v: v.replace("_", "\\_")
    art = []
    for r in csv.DictReader(open(os.path.join(data, "artifacts.csv"))):
        art.append(f"{r['kind']} & \\href{{{r['url']}}}{{\\nolinkurl{{{r['id']}}}}} & \\texttt{{{r['revision'][:12]}}} & "
                   f"{r['holds']} & {r['used_by']} \\\\")
    open(os.path.join(out, "artifacts.tex"), "w").write(
        "% Generated by scripts/paper_data.py from data/artifacts.csv; do not edit.\n" + "\n".join(art) + "\n")
    builds = []
    for r in csv.DictReader(open(os.path.join(data, "builds.csv"))):
        commit = f"\\texttt{{{r['commit'][:12]}}}" + (f"\\newline (\\texttt{{{r['upstream_commit'][:12]}}})"
                                                    if r["upstream_commit"] else "")
        builds.append(f"{r['repo']} & {commit} & \\texttt{{{tex(r['binary'])}}} & "
                      f"\\texttt{{{r['sha256'][:16]}}} & {r['used_for']} \\\\")
    open(os.path.join(out, "builds.tex"), "w").write(
        "% Generated by scripts/paper_data.py from data/builds.csv; do not edit.\n" + "\n".join(builds) + "\n")

    # Counts the method diagram prints, as macros.
    macros = {"VimItems": st["sections"]["items"], "VimCandidates": fw["admission"]["candidates"],
              "VimAdmitted": fw["admission"]["admitted"], "VimOracle": fw["attempts"]["oracle"]["tasks_solved"],
              "VimBwProposals": bw["proposals"]["proposed"], "VimBwReached": bw["attempts"]["reproduce-attempts"]["tasks_solved"],
              "VimBwAdmitted": bw["admission"]["admitted"], "VimExams": 100,
              "TeacherExamPct": f"{100 * teacher['passes'] / teacher['attempts']:.0f}", "TeacherExamPasses": teacher["passes"],
              "TeacherExamAttempts": teacher["attempts"], "TeacherExamSolved": teacher["exams_solved"],
              "TeacherFirstAttempt": f"{teacher['first_attempt_rate']:.2f}",
              "LoopFourGOnePasses": g1["passes"], "LoopFourGOneAttempts": g1["attempts"],
              "LoopFourGOneBasePasses": g1["base_passes"], "LoopFourGOneBaseAttempts": g1["base_attempts"],
              "LoopFourGOneWins": g1["vs_base"]["wins"], "LoopFourGOneLosses": g1["vs_base"]["losses"],
              "LoopFourGOneP": f"{g1['vs_base']['p_one_sided']:.5f}".rstrip("0"),
              "LoopFourGOneSolved": g1["exams_solved"],
              "LoopFourGOneHeldout": f"{g1['release_heldout']['passes'] / g1['release_heldout']['attempts']:.3f}",
              "LoopFourGOneHeldoutBase": f"{g1['release_heldout']['base_passes'] / g1['release_heldout']['base_attempts']:.3f}",
              "StudentOnlyPasses": s_only["passes"], "StudentOnlyAttempts": s_only["attempts"],
              "StudentOnlyBaseAttempts": s_only["base_attempts"]}
    open(os.path.join(out, "numbers.tex"), "w").write(
        "% Generated by scripts/paper_data.py from data/; do not edit.\n"
        + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items()))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
